export const civicBodies: CivicBody[] = citySeeds.flatMap((seed) => {
  const bodies = [
    createBody(seed, seed.municipal, "municipal", MUNICIPAL_DEPARTMENTS, [0, 0]),
    createBody(seed, seed.electricity, "electricity", ["electricity"], [0.01, 0.01]),
    createBody(seed, seed.water, "water", ["water", "drainage"], [-0.01, 0.008]),
  ];

  if (seed.traffic) {
    bodies.push(createBody(seed, seed.traffic, "traffic", ["traffic"], [0.008, -0.01]));
  }

  return bodies;
});

export function getCivicBodyById(id: string) {
  return civicBodies.find((body) => body.id === id);
}

export function getCivicBodiesByIds(ids: string[]) {
  return ids
    .map((id) => getCivicBodyById(id))
    .filter((body): body is CivicBody => Boolean(body));
}

export function listCoveredCities() {
  return [...new Set(civicBodies.map((body) => `${body.city}, ${body.state}`))].sort();
}
