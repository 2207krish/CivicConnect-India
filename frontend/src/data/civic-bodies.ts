interface OfficeSeed {
  name: string;
  shortName: string;
  address: string;
  pincode: string;
  email: string;
  phone: string;
  website?: string;
}

interface CitySeed {
  city: string;
  state: string;
  prefixes: string[];
  lat: number;
  lng: number;
  municipal: OfficeSeed;
  electricity: OfficeSeed;
  water: OfficeSeed;
  traffic?: OfficeSeed;
}

function createBody(
  seed: CitySeed,
  office: OfficeSeed,
  type: CivicBodyType,
  departments: Department[],
  offset: [number, number]
): CivicBody {
  return {
    id: `${type}-${seed.city.toLowerCase().replace(/\s+/g, "-")}`,
    name: office.name,
    shortName: office.shortName,
    type,
    departments,
    address: office.address,
    city: seed.city,
    state: seed.state,
    pincode: office.pincode,
    pincodePrefixes: seed.prefixes,
    email: office.email,
    phone: office.phone,
    website: office.website,
    lat: seed.lat + offset[0],
    lng: seed.lng + offset[1],
    officeHours: "Mon–Sat, 10:00 AM – 5:00 PM",
  };
}

